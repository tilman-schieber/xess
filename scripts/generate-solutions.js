// scripts/generate-solutions.js
// Solves every puzzle that appears in a track and writes src/puzzles/solutions.js.
// The shortest solution is the source of truth for par, hints and tutorial coaching.
//
// Run after adding or changing a puzzle:  node scripts/generate-solutions.js

import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import catalogue from '../src/puzzles/catalogue.js'
import tracks from '../src/puzzles/tracks.js'
import { solveWithPath } from '../src/puzzles/solver.js'

const MAX_DEPTH = 60
const outPath = fileURLToPath(new URL('../src/puzzles/solutions.js', import.meta.url))

const lines = []
let failed = false

for (const track of tracks) {
  lines.push(`  // ${track.title}`)
  for (const id of track.puzzleIds) {
    const raw = catalogue.find(entry => entry.id === id)
    if (!raw) {
      console.error(`✗ ${id}: not in catalogue`)
      failed = true
      continue
    }
    const started = Date.now()
    const result = solveWithPath(raw, MAX_DEPTH)
    if (!result.solvable) {
      console.error(`✗ ${id}: no solution within ${MAX_DEPTH} moves`)
      failed = true
      continue
    }
    const moves = result.moves.map(move => `${move.from}>${move.to}`).join(' ')
    lines.push(`  '${id}': '${moves}',`)
    console.log(
      `✓ ${track.id.padEnd(9)} ${id.padEnd(13)} par ${String(result.minMoves).padStart(2)}`
      + `  ${result.statesExplored.toLocaleString().padStart(9)} states  ${Date.now() - started}ms`,
    )
  }
}

if (failed) process.exit(1)

writeFileSync(outPath, `// src/puzzles/solutions.js
// GENERATED by scripts/generate-solutions.js — do not edit by hand.
// One shortest solution per track puzzle, as space-separated "from>to" moves.

const encoded = {
${lines.join('\n')}
}

const solutions = Object.fromEntries(
  Object.entries(encoded).map(([id, moves]) => [
    id,
    moves.split(' ').map((move) => {
      const [from, to] = move.split('>')
      return { from, to }
    }),
  ]),
)

export default solutions
`)
console.log(`\nWrote ${outPath}`)
